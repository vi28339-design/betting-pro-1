from model import poisson_over, calibrate_probability, odds_divergence


def с_результативный(значения, r, линия, кэфы):
    if r.get("total_exp", 0) > линия + 2:
        return {"сработала": True, "вес": 2, "текст": "Результативный матч",
                "рекомендация": f"ТБ {линия}"}
    return {"сработала": False, "вес": 0, "текст": "", "рекомендация": None}


def с_низовой(значения, r, линия, кэфы):
    if r.get("total_exp", 0) < линия - 2:
        return {"сработала": True, "вес": 2, "текст": "Низовой матч",
                "рекомендация": f"ТМ {линия}"}
    return {"сработала": False, "вес": 0, "текст": "", "рекомендация": None}


def с_явный_фаворит(значения, r, линия, кэфы):
    if r.get("p1", 0) > 0.65 and кэфы.get("п1", 0) > 1.50:
        return {"сработала": True, "вес": 2, "текст": "Явный фаворит П1",
                "рекомендация": "П1"}
    return {"сработала": False, "вес": 0, "текст": "", "рекомендация": None}


def с_явный_фаворит2(значения, r, линия, кэфы):
    if r.get("p2", 0) > 0.65 and кэфы.get("п2", 0) > 1.50:
        return {"сработала": True, "вес": 2, "текст": "Явный фаворит П2",
                "рекомендация": "П2"}
    return {"сработала": False, "вес": 0, "текст": "", "рекомендация": None}


def с_ничья_маловероятна(значения, r, линия, кэфы):
    if r.get("px", 1) < 0.15:
        лучший = "П1" if r.get("p1", 0) > r.get("p2", 0) else "П2"
        return {"сработала": True, "вес": 1, "текст": "Ничья маловероятна",
                "рекомендация": лучший}
    return {"сработала": False, "вес": 0, "текст": "", "рекомендация": None}


def с_высокий_тотал(значения, r, линия, кэфы):
    if r.get("total_exp", 0) > 12:
        return {"сработала": True, "вес": 3, "текст": "Очень результативный",
                "рекомендация": f"ТБ {линия}"}
    return {"сработала": False, "вес": 0, "текст": "", "рекомендация": None}


def с_перевес_по_эло(значения, r, линия, кэфы):
    elo_b = значения.get("elo_boost", 1.0)
    if elo_b > 1.10 and кэфы.get("п1", 0) > 1.7:
        return {"сработала": True, "вес": 2, "текст": "Elo перевес П1",
                "рекомендация": "П1"}
    elif elo_b < 0.90 and кэфы.get("п2", 0) > 1.7:
        return {"сработала": True, "вес": 2, "текст": "Elo перевес П2",
                "рекомендация": "П2"}
    return {"сработала": False, "вес": 0, "текст": "", "рекомендация": None}


def с_домашнее_преимущество(значения, r, линия, кэфы):
    к1з = значения.get("к1з", 0)
    к2з = значения.get("к2з", 0)
    if к2з > 0 and к1з > к2з * 1.3 and кэфы.get("п1", 0) > 1.5:
        return {"сработала": True, "вес": 2, "текст": "Домашнее преимущество",
                "рекомендация": "П1"}
    return {"сработала": False, "вес": 0, "текст": "", "рекомендация": None}


def с_расхождение_с_рынком(значения, r, линия, кэфы):
    к_тб = кэфы.get("тб", 0)
    к_тм = кэфы.get("тм", 0)
    if к_тб <= 1.01 or к_тм <= 1.01:
        return {"сработала": False, "вес": 0, "текст": "", "рекомендация": None}
    p_тб = calibrate_probability(poisson_over(r.get("total_exp", 0), линия))
    p_тм = 1 - p_тб
    div_тб, _ = odds_divergence(p_тб, (к_тб, к_тм), "over")
    div_тм, _ = odds_divergence(p_тм, (к_тб, к_тм), "under")
    if div_тб > 0.08:
        return {"сработала": True, "вес": 3, "текст": "Модель выше рынка (ТБ)",
                "рекомендация": f"ТБ {линия}"}
    if div_тм > 0.08:
        return {"сработала": True, "вес": 3, "текст": "Модель выше рынка (ТМ)",
                "рекомендация": f"ТМ {линия}"}
    return {"сработала": False, "вес": 0, "текст": "", "рекомендация": None}


ВСЕ_СТРАТЕГИИ = [
    с_результативный, с_низовой, с_явный_фаворит, с_явный_фаворит2,
    с_ничья_маловероятна, с_высокий_тотал, с_перевес_по_эло,
    с_домашнее_преимущество, с_расхождение_с_рынком,
]


def имена_стратегий():
    return [
        ("с_результативный", "Результативный матч"),
        ("с_низовой", "Низовой матч"),
        ("с_явный_фаворит", "Явный фаворит П1"),
        ("с_явный_фаворит2", "Явный фаворит П2"),
        ("с_ничья_маловероятна", "Ничья маловероятна"),
        ("с_высокий_тотал", "Очень результативный"),
        ("с_перевес_по_эло", "Elo-перевес"),
        ("с_домашнее_преимущество", "Домашнее преимущество"),
        ("с_расхождение_с_рынком", "Расхождение с рынком"),
    ]


def читаемое_имя(имя_функции):
    for имя, читаемое in имена_стратегий():
        if имя == имя_функции:
            return читаемое
    return имя_функции


def автоматический_анализ(значения, r, линия, кэфы, включённые=None):
    сработали = []
    for стратегия in ВСЕ_СТРАТЕГИИ:
        имя = стратегия.__name__
        if включённые is not None and not включённые.get(имя, True):
            continue
        try:
            рез = стратегия(значения, r, линия, кэфы)
            if рез.get("сработала"):
                рез["имя"] = имя
                рез["читаемое"] = читаемое_имя(имя)
                сработали.append(рез)
        except Exception:
            continue

    рекомендации = {}
    for s in сработали:
        рек = s.get("рекомендация")
        if рек:
            рекомендации[рек] = рекомендации.get(рек, 0) + s["вес"]

    if рекомендации:
        лучшая = max(рекомендации, key=рекомендации.get)
        сила = рекомендации[лучшая]
    else:
        лучшая = None
        сила = 0

    return {"сработали": сработали, "рекомендации": рекомендации,
            "лучшая": лучшая, "сила": сила}