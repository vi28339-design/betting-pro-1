import re

СЛОВАРЬ = {
    "тиrры": "Тигры", "тигрь": "Тигры",
    "льдины": "Льдины", "кремлевц": "Кремлевцы",
    "культуролог": "Культурологи",
}


def разобрать_текст(текст):
    результат = {"линия": None, "кэф_тб": None, "кэф_тм": None,
                 "кэф_п1": None, "кэф_х": None, "кэф_п2": None,
                 "команда1": None, "команда2": None,
                 "сырой_текст": текст or "", "уверенность": 0}
    if not текст:
        return результат

    строки = [s.strip() for s in текст.split("\n") if s.strip()]
    найдено = 0

    for паттерн in [r"[Тт][Бб]\s*[:\-]?\s*(\d{1,2}[.,]\d)",
                    r"[Тт][Мм]\s*[:\-]?\s*(\d{1,2}[.,]\d)",
                    r"[Тт]отал[:\s]+(\d{1,2}[.,]\d)",
                    r"Total[:\s]+(\d{1,2}[.,]\d)"]:
        m = re.search(паттерн, текст)
        if m:
            результат["линия"] = _безопасный_флоат(m.group(1))
            if результат["линия"]:
                найдено += 1
                break

    if результат["линия"] is None:
        for строка in строки:
            if "тотал" in строка.lower():
                числа = re.findall(r"(\d{1,2}[.,]\d)", строка)
                if числа:
                    результат["линия"] = _безопасный_флоат(числа[0])
                    if результат["линия"]:
                        найдено += 1
                        break

    for паттерн, ключ in [
        (r"[Тт][Бб][^\d\n]{0,15}(\d{1,2}[.,]\d{1,2})", "кэф_тб"),
        (r"[Тт][Мм][^\d\n]{0,15}(\d{1,2}[.,]\d{1,2})", "кэф_тм"),
        (r"(?:П1|W1)[^\d\n]{0,10}(\d{1,2}[.,]\d{1,2})", "кэф_п1"),
        (r"(?:П2|W2)[^\d\n]{0,10}(\d{1,2}[.,]\d{1,2})", "кэф_п2"),
        (r"(?:Ничья|[ХXх])\s*[:\-]?\s*(\d{1,2}[.,]\d{1,2})", "кэф_х"),
    ]:
        if результат[ключ] is not None:
            continue
        m = re.search(паттерн, текст)
        if m:
            v = _безопасный_флоат(m.group(1))
            if v and _валидный_кэф(v):
                результат[ключ] = v
                найдено += 1

    все_числа = re.findall(r"\b(\d{1,2}[.,]\d{1,2})\b", текст)
    кэфы = []
    for n in все_числа:
        v = _безопасный_флоат(n)
        if v and _валидный_кэф(v):
            кэфы.append(v)

    if результат["кэф_тб"] is None and len(кэфы) >= 2:
        результат["кэф_тб"] = кэфы[0]
        результат["кэф_тм"] = кэфы[1]
        найдено += 2
    if результат["кэф_п1"] is None and len(кэфы) >= 3:
        результат["кэф_п1"] = кэфы[0]
        результат["кэф_п2"] = кэфы[1]

    m = re.search(
        r"([А-ЯЁA-Z][А-Яа-яЁёA-Za-z\s]{2,25})\s*(?:[-–—]|vs\.?|—)\s*"
        r"([А-ЯЁA-Z][А-Яа-яЁёA-Za-z\s]{2,25})", текст)
    if m:
        результат["команда1"] = _исправить_слово(m.group(1).strip())
        результат["команда2"] = _исправить_слово(m.group(2).strip())
        найдено += 1

    результат["уверенность"] = min(100, int(найдено / 7 * 100))
    return результат


def _безопасный_флоат(строка):
    try:
        return float(строка.replace(",", "."))
    except (ValueError, AttributeError):
        return None


def _валидный_кэф(кэф):
    return 1.01 <= кэф <= 20.0


def _исправить_слово(слово):
    низкое = слово.lower().strip()
    return СЛОВАРЬ.get(низкое, слово)